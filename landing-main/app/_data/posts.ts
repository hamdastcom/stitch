export function getAllPosts(): Post[] {
  return [...posts].sort((a, b) => (a.publishedAt < b.publishedAt ? 1 : -1));
}

export function getPostBySlug(slug: string): Post | undefined {
  return posts.find((post) => post.slug === slug);
}

export function getRelatedPosts(slug: string, limit = 3): Post[] {
  const current = getPostBySlug(slug);
  if (!current) return [];

  const sameCategory = getAllPosts().filter(
    (post) => post.slug !== slug && post.category === current.category,
  );
  if (sameCategory.length >= limit) return sameCategory.slice(0, limit);

  const extras = getAllPosts().filter(
    (post) =>
      post.slug !== slug &&
      !sameCategory.some((item) => item.slug === post.slug),
  );
  return [...sameCategory, ...extras].slice(0, limit);
}

export function getPostCounts() {
  const all = posts.length;
  const learn = posts.filter((post) => post.category === "learn").length;
  const blog = posts.filter((post) => post.category === "blog").length;
  const newsletter = posts.filter((post) => post.category === "newsletter").length;
  return { all, learn, blog, newsletter };
}
